//! Python source emitter for verified AMI candidates.
//!
//! The proof covers the AMI expression; this module prints it with the same
//! wrapping semantics as `Expr::try_eval_bits`: Python integers are unbounded,
//! so every operation is cut to 32 bits (64 for `wide` rules). Equivalence is
//! checked by `tests/py_emit.rs`, not proven.

use axiom_ami::Expr;
use axiom_parser::{Contract, Type};

use crate::js::{list_parts, param_groups, settle_sizes};

/// Prints one AMI expression; every value is an unsigned word of `bits` bits.
fn expr(e: &Expr, bits: u32) -> String {
    let x = |e: &Expr| expr(e, bits);
    let mask = |s: String| format!("(({s}) & _M{bits})");
    let call = |f: &str, l: &Expr, r: &Expr| format!("{f}({}, {}, {bits})", x(l), x(r));
    let cmp = |op: &str, l: &Expr, r: &Expr| format!("int(({}) {op} ({}))", x(l), x(r));
    let scmp = |op: &str, l: &Expr, r: &Expr| {
        format!("int(_s({}, {bits}) {op} _s({}, {bits}))", x(l), x(r))
    };
    match e {
        Expr::Arg(i) => format!("_a{i}"),
        Expr::Const(v) => v.to_string(),
        Expr::Add(l, r) => mask(format!("({}) + ({})", x(l), x(r))),
        Expr::Sub(l, r) => mask(format!("({}) - ({})", x(l), x(r))),
        Expr::Mul(l, r) => mask(format!("({}) * ({})", x(l), x(r))),
        Expr::Div(l, r) => call("_div", l, r),
        Expr::Rem(l, r) => call("_rem", l, r),
        Expr::SDiv(l, r) => call("_sdiv", l, r),
        Expr::SRem(l, r) => call("_srem", l, r),
        Expr::Shl(l, r) => mask(format!("({}) << (({}) & {})", x(l), x(r), bits - 1)),
        Expr::BitAnd(l, r) => format!("(({}) & ({}))", x(l), x(r)),
        Expr::BitOr(l, r) => format!("(({}) | ({}))", x(l), x(r)),
        Expr::BitXor(l, r) => format!("(({}) ^ ({}))", x(l), x(r)),
        Expr::Eq(l, r) => cmp("==", l, r),
        Expr::Ne(l, r) => cmp("!=", l, r),
        Expr::Lt(l, r) => cmp("<", l, r),
        Expr::Le(l, r) => cmp("<=", l, r),
        Expr::Gt(l, r) => cmp(">", l, r),
        Expr::Ge(l, r) => cmp(">=", l, r),
        Expr::SLt(l, r) => scmp("<", l, r),
        Expr::SLe(l, r) => scmp("<=", l, r),
        Expr::SGt(l, r) => scmp(">", l, r),
        Expr::SGe(l, r) => scmp(">=", l, r),
        Expr::And(l, r) => format!("int(({}) != 0 and ({}) != 0)", x(l), x(r)),
        Expr::Or(l, r) => format!("int(({}) != 0 or ({}) != 0)", x(l), x(r)),
        Expr::Select {
            condition,
            then_branch,
            else_branch,
        } => format!(
            "(({}) if ({}) != 0 else ({}))",
            x(then_branch),
            x(condition),
            x(else_branch)
        ),
        Expr::ArrayGet { elements, index } => {
            let arms: String = elements
                .iter()
                .enumerate()
                .map(|(i, e)| format!("({}) if _i == {i} else ", x(e)))
                .collect();
            format!(
                "(lambda _i: {arms}_fail(\"fixed array index is out of bounds\"))({})",
                x(index)
            )
        }
        Expr::Guard { condition, value } => format!(
            "(({}) if ({}) != 0 else _fail(\"verified runtime guard failed\"))",
            x(value),
            x(condition)
        ),
    }
}

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield",
];

/// Builtins the emitted Python calls; a rule or input with one of these names would shadow it.
const BUILTINS: &[&str] = &["abs", "int", "isinstance", "len", "list", "range", "tuple"];

/// A Python name for a rule or input: keywords and builtins get a trailing `_`.
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) || BUILTINS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

const HEADER: &str = r#"# Generated by axiom. Do not edit.
# Source-level proof covers the AMI expression; this Python is checked by differential tests, not proven.

_M32 = 0xFFFFFFFF
_M64 = 0xFFFFFFFFFFFFFFFF


class AxiomError(Exception):
    """A rule was called outside its `need` lines, or a checked operation failed."""


def _fail(message):
    raise AxiomError(message)


def _s(value, bits):
    return value - (1 << bits) if value >> (bits - 1) else value


def _div(l, r, bits):
    if r == 0:
        _fail("division by zero")
    return l // r


def _rem(l, r, bits):
    if r == 0:
        _fail("division by zero")
    return l % r


def _sdiv(l, r, bits):
    a, b = _s(l, bits), _s(r, bits)
    if b == 0 or (a == -(1 << (bits - 1)) and b == -1):
        _fail("division by zero or overflow")
    q = abs(a) // abs(b)
    return (q if (a < 0) == (b < 0) else -q) & ((1 << bits) - 1)


def _srem(l, r, bits):
    a, b = _s(l, bits), _s(r, bits)
    if b == 0 or (a == -(1 << (bits - 1)) and b == -1):
        _fail("division by zero or overflow")
    m = abs(a) % abs(b)
    return (-m if a < 0 else m) & ((1 << bits) - 1)


def _word(name, value, low, high):
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise TypeError(f"{name}: expected an integer from {low} to {high}")
    return value


def _flag(name, value):
    if not isinstance(value, bool):
        raise TypeError(f"{name}: expected True or False")
    return int(value)
"#;

/// Returns one Python module exporting every given contract.
pub fn emit_module(items: &[(&Contract, &Expr, Option<&Expr>)]) -> Result<String, String> {
    let mut out = HEADER.to_string();
    for (contract, candidate, guard) in items {
        out += "\n\n";
        out += &emit_function(contract, candidate, *guard)?;
    }
    let contracts: Vec<&Contract> = items.iter().map(|(c, _, _)| *c).collect();
    for contract in &contracts {
        if let Some((base, parts)) = list_parts(contract, &contracts) {
            out += "\n\n";
            out += &list_wrapper(base, &parts);
        }
    }
    for contract in &contracts {
        if let Some(rule) = &contract.list {
            out += "\n\n";
            out += &any_length_wrapper(contract, rule);
        }
    }
    let sizes = settle_sizes(&contracts);
    if !sizes.is_empty() {
        out += "\n\n";
        out += &settle_wrapper(&sizes);
    }
    Ok(out)
}

/// Checks one input and lowers it to an unsigned word `a{index}`.
fn lower(name: &str, ty: &Type, bits: u32, index: usize) -> Result<String, String> {
    Ok(match ty {
        Type::U32 => format!(
            "    _a{index} = _word(\"{name}\", {name}, 0, {})\n",
            (1u128 << bits) - 1
        ),
        Type::I32 => format!(
            "    _a{index} = _word(\"{name}\", {name}, {}, {}) & _M{bits}\n",
            -(1i128 << (bits - 1)),
            (1i128 << (bits - 1)) - 1
        ),
        Type::Bool => format!("    _a{index} = _flag(\"{name}\", {name})\n"),
        other => {
            return Err(format!(
                "Python output supports only u32, i32 and bool, found {other:?}"
            ));
        }
    })
}

fn emit_function(
    contract: &Contract,
    candidate: &Expr,
    guard: Option<&Expr>,
) -> Result<String, String> {
    let bits = if contract.wide { 64 } else { 32 };
    let names: Vec<String> = contract.params.iter().map(|p| ident(&p.name)).collect();
    let mut body = String::new();
    for (index, (p, name)) in contract.params.iter().zip(&names).enumerate() {
        body += &lower(name, &p.ty, bits, index)?;
    }
    if let Some(g) = guard {
        body += &format!(
            "    if ({}) == 0:\n        _fail(\"{}: input violates a requires clause\")\n",
            expr(g, bits),
            contract.name
        );
    }
    let result = expr(candidate, bits);
    let result = match contract.return_type {
        Type::Bool => format!("({result}) != 0"),
        Type::I32 => format!("_s({result}, {bits})"),
        Type::U32 => result,
        ref other => {
            return Err(format!(
                "Python output supports only u32, i32 and bool, found {other:?}"
            ));
        }
    };
    Ok(format!(
        "def {}({}):\n{body}    return {result}\n",
        ident(&contract.name),
        names.join(", "),
    ))
}

/// `f(x, y)` over `f_1..f_N` when the rule's answer was a list; `x_1..x_k`
/// inputs become one list `x` of k items.
fn list_wrapper(base: &str, parts: &[&Contract]) -> String {
    let mut params = Vec::new();
    let mut checks = String::new();
    let mut args = Vec::new();
    for (name, size, _) in param_groups(parts[0]) {
        let name = ident(&name);
        if size > 0 {
            checks += &format!(
                "    if len({name}) != {size}:\n        raise TypeError(\"{base}: {name} must have {size} items\")\n"
            );
            args.extend((0..size).map(|k| format!("{name}[{k}]")));
        } else {
            args.push(name.clone());
        }
        params.push(name);
    }
    let calls: Vec<String> = parts
        .iter()
        .map(|c| format!("{}({})", ident(&c.name), args.join(", ")))
        .collect();
    format!(
        "def {}({}):\n{checks}    return [{}]\n",
        ident(base),
        params.join(", "),
        calls.join(", ")
    )
}

/// `cart(prices)` for a rule over lists of any length: checks the length,
/// adds each item rule over the items in a loop, then calls the core.
fn any_length_wrapper(core: &Contract, rule: &axiom_parser::ListRule) -> String {
    let names: Vec<String> = rule.params.iter().map(|(p, _)| ident(p)).collect();
    let first = rule.params.iter().position(|(_, list)| *list).unwrap_or(0);
    let mut checks = String::new();
    for (i, (_, list)) in rule.params.iter().enumerate() {
        if *list {
            checks += &format!(
                "    if not isinstance({0}, (list, tuple)) or len({0}) != len({1}):\n        raise TypeError(\"{2}: {0} must be a list as long as the other lists\")\n",
                names[i], names[first], rule.name
            );
        }
    }
    let item_args: Vec<String> = rule
        .params
        .iter()
        .zip(&names)
        .map(|((_, list), name)| {
            if *list {
                format!("{name}[_i]")
            } else {
                name.clone()
            }
        })
        .collect();
    let mut sums = String::new();
    let mut body = String::new();
    for (k, (item, fold)) in rule.items.iter().zip(&rule.folds).enumerate() {
        sums += &format!("    sum{} = 0\n", k + 1);
        let call = format!("{}({})", ident(item), item_args.join(", "));
        body += &match fold {
            axiom_parser::Fold::Sum => format!("        sum{} += {call}\n", k + 1),
            axiom_parser::Fold::Min | axiom_parser::Fold::Max => format!(
                "        _v = {call}\n        if _i == 0 or _v {} sum{1}:\n            sum{1} = _v\n",
                if *fold == axiom_parser::Fold::Min {
                    "<"
                } else {
                    ">"
                },
                k + 1
            ),
        };
    }
    let mut core_args: Vec<String> = if rule.each {
        item_args.clone()
    } else {
        rule.params
            .iter()
            .zip(&names)
            .filter(|((_, list), _)| !*list)
            .map(|(_, name)| name.clone())
            .collect()
    };
    core_args.push("_n".into());
    core_args.extend((1..=rule.items.len()).map(|k| format!("sum{k}")));
    if !body.is_empty() {
        body = format!("    for _i in range(_n):\n{body}");
    }
    let call = format!("{}({})", ident(&core.name), core_args.join(", "));
    let tail = if rule.each {
        format!("[{call} for _i in range(_n)]")
    } else {
        call
    };
    format!(
        "def {}({}):\n{checks}    _n = len({})\n    if {}_n > {}:\n        _fail(\"{}: input violates a requires clause\")\n{sums}{body}    return {tail}\n",
        ident(&rule.name),
        names.join(", "),
        names[first],
        crate::rs::too_few(rule, "_n", "or"),
        rule.max,
        rule.name,
    )
}

/// `settle(owe)`: N from the list length, N * N transfers, item (i-1)*N+j
/// from person i to person j.
fn settle_wrapper(sizes: &[usize]) -> String {
    let mut cases = String::new();
    for n in sizes {
        let calls: Vec<String> = (1..=*n)
            .flat_map(|i| (1..=*n).map(move |j| format!("settle_{n}_{i}_{j}(*owe)")))
            .collect();
        cases += &format!(
            "    if len(owe) == {n}:\n        return [{}]\n",
            calls.join(", ")
        );
    }
    let list: Vec<String> = sizes.iter().map(usize::to_string).collect();
    format!(
        "def settle(owe):\n{cases}    raise TypeError(\"settle: owe must have {} items\")\n",
        list.join(" or ")
    )
}

